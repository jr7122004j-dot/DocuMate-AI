"""Token-by-token streaming sinks and handlers for DocuMate-AI.

Defines the ``TokenSink`` protocol and implementations:
    - ``TokenSink``: UI-agnostic protocol for receiving streaming tokens and
      finalizing responses.
    - ``StreamlitTokenSink``: Throttled renderer with a blinking cursor (▌)
      for Streamlit containers (without directly importing ``streamlit``).
    - ``CollectingSink``: In-memory token collector for tests and non-UI usage.
    - ``NullSink``: No-op sink for silent execution.
    - ``StreamHandler``: Backwards-compatible adapter for existing call sites.

Streaming is driven directly by ``conversation.stream_answer()`` so that ONLY
answer tokens reach the sink (preventing condense-question prompt leakage).
"""

from __future__ import annotations

import time
from typing import Any, Protocol, runtime_checkable

from documate_ai.config import STREAM_RENDER_INTERVAL_SECONDS, get_settings


@runtime_checkable
class TokenSink(Protocol):
    """Protocol for receiving streaming tokens and finalizing output."""

    def on_token(self, token: str) -> None:
        """Receive a single generated token or text delta.

        Args:
            token: Text chunk generated by the model.
        """
        ...

    def finalize(self, final_text: str | None = None) -> str:
        """Finalize the stream and optionally replace streamed text.

        This method must be idempotent.

        Args:
            final_text: If provided, replaces the streamed text with
                post-processed content (e.g. answer with citations).
                If None, the accumulated streamed text is finalized.

        Returns:
            The final rendered text.
        """
        ...


class NullSink:
    """A no-op sink that discards all tokens."""

    def on_token(self, token: str) -> None:
        """Discard the token."""
        pass

    def finalize(self, final_text: str | None = None) -> str:
        """Return final_text or empty string."""
        return final_text or ""


class CollectingSink:
    """Collects streaming tokens in memory for tests or headless consumers."""

    def __init__(self) -> None:
        self._tokens: list[str] = []
        self._final_text: str | None = None
        self._finalized: bool = False

    def on_token(self, token: str) -> None:
        """Append token to the buffer if not yet finalized."""
        if not self._finalized:
            self._tokens.append(token)

    def finalize(self, final_text: str | None = None) -> str:
        """Finalize the collection (idempotent)."""
        if not self._finalized:
            if final_text is not None:
                self._final_text = final_text
            else:
                self._final_text = "".join(self._tokens)
            self._finalized = True
        return self._final_text or ""

    @property
    def text(self) -> str:
        """Return the accumulated or finalized text."""
        if self._finalized and self._final_text is not None:
            return self._final_text
        return "".join(self._tokens)

    @property
    def tokens(self) -> list[str]:
        """Return a copy of the collected token list."""
        return list(self._tokens)


class StreamlitTokenSink:
    """Streams LLM tokens into a container with throttling and cursor effect.

    Decoupled from Streamlit: accepts any container with a ``.markdown(str)``
    method (e.g. Streamlit's ``st.empty()`` or test fakes like ``FakeContainer``).

    Attributes:
        container: A container object that supports ``.markdown(body)``.
        render_interval: Minimum time (seconds) between markdown render calls.
        cursor: Character used to represent the typing cursor.
    """

    def __init__(
        self,
        container: Any,
        render_interval: float | None = None,
        cursor: str = "▌",
    ) -> None:
        """Initialise the Streamlit token sink.

        Args:
            container: Object supporting ``.markdown(str)``.
            render_interval: Minimum seconds between UI updates. If None,
                defaults to ``settings.stream_render_interval_seconds``.
            cursor: Cursor character appended during generation.
        """
        self.container = container
        if render_interval is not None:
            self.render_interval = render_interval
        else:
            try:
                self.render_interval = get_settings().stream_render_interval_seconds
            except Exception:
                self.render_interval = STREAM_RENDER_INTERVAL_SECONDS

        self.cursor = cursor
        self._text: str = ""
        self._last_render_time: float = 0.0
        self._finalized: bool = False
        self._final_text: str | None = None

    @property
    def text(self) -> str:
        """Return the current text (finalized or accumulated)."""
        if self._finalized and self._final_text is not None:
            return self._final_text
        return self._text

    def on_token(self, token: str) -> None:
        """Accumulate token and render to container if render_interval elapsed.

        Args:
            token: New token string.
        """
        if self._finalized:
            return

        self._text += token
        now = time.monotonic()
        if (now - self._last_render_time) >= self.render_interval:
            self.container.markdown(self._text + self.cursor)
            self._last_render_time = now

    def finalize(self, final_text: str | None = None) -> str:
        """Render the final text without the cursor.

        Idempotent: subsequent calls return the existing final text without
        re-rendering.

        Args:
            final_text: Optional post-processed text (such as answer with
                appended citations). If None, accumulated text is used.

        Returns:
            The finalized text rendered into the container.
        """
        if not self._finalized:
            if final_text is not None:
                self._final_text = final_text
            else:
                self._final_text = self._text

            self.container.markdown(self._final_text)
            self._finalized = True

        return self._final_text or ""


class StreamHandler(StreamlitTokenSink):
    """Backwards-compatible adapter for existing code and test fixtures."""

    def on_llm_new_token(
        self,
        token: str | list[str | dict[str, Any]],
        **kwargs: Any,
    ) -> None:
        """Compatibility method for LangChain callback style callers."""
        if isinstance(token, str):
            text = token
        elif isinstance(token, list):
            text = "".join(
                t if isinstance(t, str) else str(t.get("text", t)) for t in token
            )
        else:
            text = str(token)
        self.on_token(text)
